"""Smaller copies of the site photographs for srcset.

For every .webp in public/photos and public/properties wider than 900px,
writes <name>-800.webp (and <name>-1200.webp when the original is wider than
1400px), then lists what exists in src/app/data/photoSizes.ts, which the
photo() helper (src/app/lib/photo.ts) reads. It also gives every photograph
a tone: the step of the site's warm monochrome ramp (TONES, cream to near
black) nearest its average lightness, which colours the photograph's place
while it loads (img[data-tone] in theme.css). Run after adding photos:

    python3 scripts/photo-variants.py
"""
import glob, os, re
from PIL import Image

# The ramp, light to dark; keep in step with img[data-tone] in src/styles/theme.css.
TONES = ['#F8F6F1', '#EDE7DF', '#DDD6CE', '#C4BBB1', '#A69D94', '#857C74', '#6B645D', '#4A443F', '#2A2623', '#1B1412']
LUM = [0.299 * int(c[1:3], 16) + 0.587 * int(c[3:5], 16) + 0.114 * int(c[5:7], 16) for c in TONES]

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLIC = os.path.join(ROOT, 'public')
sizes, tones = {}, {}
for path in sorted(glob.glob(f'{PUBLIC}/photos/*.webp') + glob.glob(f'{PUBLIC}/properties/**/*.webp', recursive=True)):
    if re.search(r'-(800|1200)\.webp$', path):
        continue
    im = Image.open(path)
    w, h = im.size
    small = im.convert('RGBA').resize((32, 32))
    if min(a for *_, a in small.getdata()) == 255:  # no tone behind a cut-out
        grey = small.convert('L').getdata()
        mean = sum(grey) / len(grey)
        tones['/' + os.path.relpath(path, PUBLIC)] = min(range(len(LUM)), key=lambda i: abs(LUM[i] - mean))
    if w <= 900:
        continue
    widths = []
    for target in (800, 1200):
        if w > target + 200:
            out = path[:-5] + f'-{target}.webp'
            if not os.path.exists(out):
                im.convert('RGB').resize((target, round(h * target / w)), Image.LANCZOS).save(out, 'WEBP', quality=78, method=6)
            widths.append(target)
    sizes['/' + os.path.relpath(path, PUBLIC)] = widths + [w]

lines = ',\n'.join(f"  '{k}': [{', '.join(map(str, v))}]" for k, v in sizes.items())
tone_lines = ',\n'.join(f"  '{k}': {v}" for k, v in tones.items())
with open(os.path.join(ROOT, 'src/app/data/photoSizes.ts'), 'w') as f:
    f.write('// Generated by scripts/photo-variants.py — widths available for each photo.\n'
            f'export const PHOTO_SIZES: Record<string, number[]> = {{\n{lines},\n}};\n\n'
            '// The step of the monochrome ramp (0 cream … 9 near black) nearest each photo\'s average lightness.\n'
            f'export const PHOTO_TONES: Record<string, number> = {{\n{tone_lines},\n}};\n')
print(len(sizes), 'photos')
