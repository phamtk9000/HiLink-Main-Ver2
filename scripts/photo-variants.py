"""Smaller copies of the site photographs for srcset.

For every .webp in public/photos and public/properties wider than 900px,
writes <name>-800.webp (and <name>-1200.webp when the original is wider than
1400px), then lists what exists in src/app/data/photoSizes.ts, which the
photo() helper (src/app/lib/photo.ts) reads. Run after adding photos:

    python3 scripts/photo-variants.py
"""
import glob, os, re
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLIC = os.path.join(ROOT, 'public')
sizes = {}
for path in sorted(glob.glob(f'{PUBLIC}/photos/*.webp') + glob.glob(f'{PUBLIC}/properties/**/*.webp', recursive=True)):
    if re.search(r'-(800|1200)\.webp$', path):
        continue
    im = Image.open(path)
    w, h = im.size
    if w <= 900:
        continue
    widths = []
    for target in (800, 1200):
        if w > target + 200:
            out = path[:-5] + f'-{target}.webp'
            if not os.path.exists(out):
                im.convert('RGB').resize((target, round(h * target / w)), Image.LANCZOS).save(out, 'WEBP', quality=78, method=6)
            widths.append(target)
    sizes['/' + os.path.relpath(path, PUBLIC)] = widths + [w]

lines = ',\n'.join(f"  '{k}': [{', '.join(map(str, v))}]" for k, v in sizes.items())
with open(os.path.join(ROOT, 'src/app/data/photoSizes.ts'), 'w') as f:
    f.write('// Generated by scripts/photo-variants.py — widths available for each photo.\n'
            f'export const PHOTO_SIZES: Record<string, number[]> = {{\n{lines},\n}};\n')
print(len(sizes), 'photos')
